/** بعد از هر اسلاید درسی که imageHint دارد، یک اسلاید تصویر بزرگ می‌آید. */
function buildDeck(sources: SlideSource[]): Slide[] {
  const deck: Slide[] = [];
  for (const s of sources) {
    const kind = s.kind ?? "lesson";
    if (kind === "lesson" && s.imageHint) {
      const { imageHint, ...rest } = s;
      deck.push({ ...rest, kind: "lesson" });
      deck.push({
        id: `${s.id}-visual`,
        kind: "visual",
        chapter: s.chapter,
        title: s.title,
        goal: "",
        body: imageHint,
        bullets: [],
        terms: [],
        mistakes: [],
        imageHint,
        imageId: s.id,
      });
    } else {
      deck.push({ ...s, kind });
    }
  }
  return deck;
}

export const slides = buildDeck(slideSources);
