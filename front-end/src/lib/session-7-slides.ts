function buildDeck(sources: SlideSource[]): Slide[] {
  const deck: Slide[] = [];
  for (const s of sources) {
    const kind = s.kind ?? "lesson";
    if (kind === "lesson" && s.imageHint) {
      const { imageHint, ...rest } = s;
      deck.push({ ...rest, kind: "lesson" });
      deck.push({
        id: `${s.id}-visual`,
        kind: "visual",
        chapter: s.chapter,
        title: s.title,
        goal: "",
        body: imageHint,
        bullets: [],
        terms: [],
        mistakes: [],
        imageHint,
        // تصاویر مشترک با جلسهٔ پنجم
        imageId: `/session_5/${s.id}.png`,
      });
    } else {
      deck.push({ ...s, kind });
    }
  }
  return deck;
}

