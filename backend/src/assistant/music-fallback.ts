function isOffTopic(text: string) {
  return /سیاست|انتخابات|پزشکی|دارو|کدنویس|برنامه.?نویس|جاوا|پایتون|فوتبال|فیلم|سریال|شایعه|رمز ارز|بورس|تکلیف مدرسه|ریاضی|فیزیک/.test(
    text,
  );
}

function isMusic(text: string) {
  return /موسیقی|پیانو|تمرین|نت|گام|ریتم|تئوری|هانون|لگاتو|استاکاتو|آرپژ|مترونوم|رپرتوار|سلفژ|آکورد|میزان|کلاویه|انگشت|قطعه|اتود|سونات|باخ|چوپین|موتزارت/.test(
    text,
  );
}

export function localMusicReply(question: string) {
  const text = question.trim();
  if (!text) return REFUSAL;
  if (isOffTopic(text) && !isMusic(text)) return REFUSAL;

  for (const topic of TOPICS) {
    if (topic.test.test(text)) return topic.reply;
  }

  if (isMusic(text)) return GENERIC_MUSIC;
  return REFUSAL;
}
